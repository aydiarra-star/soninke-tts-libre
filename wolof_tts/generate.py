import csv
import hashlib
import json
import zipfile
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import soundfile as sf
import torch
from parler_tts import ParlerTTSForConditionalGeneration
from transformers import AutoTokenizer

MODEL_ID = "CONCREE/Adia_TTS"
OUT = Path("wolof_tts_outputs")
OUT.mkdir(parents=True, exist_ok=True)

# Linguistic reference supplied and validated by the user.
WORDS = [
    {"id": "jerejef", "wolof": "Jërëjëf", "french": "Merci"},
    {"id": "ker", "wolof": "Kër", "french": "Maison"},
    {"id": "ngew", "wolof": "Ñëw", "french": "Venir"},
]

device = "cuda:0" if torch.cuda.is_available() else "cpu"
print(f"Loading {MODEL_ID} on {device}; torch={torch.__version__}")
model = ParlerTTSForConditionalGeneration.from_pretrained(MODEL_ID).to(device)
tokenizer = AutoTokenizer.from_pretrained(MODEL_ID)
description = "A clear, natural Wolof-speaking voice for language learning."
description_ids = tokenizer(description, return_tensors='pt').input_ids.to(device)
manifest = []

for item in WORDS:
    text = item["wolof"]
    print(f"Generating: {text} ({item['french']})")
    prompt_ids = tokenizer(text, return_tensors='pt').input_ids.to(device)
    with torch.inference_mode():
        audio = model.generate(input_ids=description_ids, prompt_input_ids=prompt_ids)
    audio_np = audio.detach().cpu().numpy().squeeze()
    if audio_np.ndim != 1 or audio_np.size == 0:
        raise RuntimeError(f"Model returned invalid audio for {item['id']}")
    sample_rate = int(getattr(model.config, "sampling_rate", 24000))
    path = OUT / f"{item['id']}.wav"
    sf.write(str(path), audio_np, sample_rate, subtype="PCM_16")
    with sf.SoundFile(path) as wav:
        frames, rate, channels, subtype = len(wav), wav.samplerate, wav.channels, wav.subtype
        duration = frames / rate
        samples = wav.read(dtype="float32")
    if rate < 8000 or channels != 1 or frames <= 0 or not (0.15 <= duration <= 15):
        raise RuntimeError(f"Technical WAV validation failed: {path}")
    if not np.isfinite(samples).all():
        raise RuntimeError(f"Audio contains non-finite samples: {path}")
    peak = float(np.max(np.abs(samples)))
    if peak <= 0.0001:
        raise RuntimeError(f"Audio is silent: {path}")
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    manifest.append({
        **item,
        "file": path.name, "model": MODEL_ID, "sample_rate_hz": rate,
        "channels": channels, "subtype": subtype, "duration_seconds": round(duration, 3),
        "peak_amplitude": round(peak, 6), "sha256": digest,
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "technical_validation": "passed", "human_pronunciation_validation": "pending",
        "note": "Generated by Wolof TTS model; not yet human-validated for pronunciation."
    })
    print(f"VERIFIED {path}: {duration:.2f}s, {rate}Hz, {channels}ch, sha256={digest}")

(OUT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
with (OUT / "manifest.csv").open("w", newline="", encoding="utf-8-sig") as f:
    writer = csv.DictWriter(f, fieldnames=list(manifest[0].keys()))
    writer.writeheader()
    writer.writerows(manifest)

zip_path = Path("wolof_tts_audio.zip")
with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED) as archive:
    for path in sorted(OUT.iterdir()):
        archive.write(path, arcname=path.name)
print(f"SUCCESS: {len(manifest)} WAVs generated and technically verified; archive={zip_path}")